day. By end of day I've been heads-down in a Claude Code session on a ticket, and
the full picture of what I actually did is already right here in the session. But to
log it I have to stop, switch over to Jira, find my ticket, then sit there trying to
remember and summarize everything I worked on, write a comment that reads properly,
and log the hours in the format my team expects. It's a small thing but I do it
every single day, and it drags me out of where I'm actually working.

What I want is to not leave Claude Code for any of it. At the end of the day I just
say "log my hours on <ticket>", and since you already know what we worked on this
session, you draft the comment and a sensible number of hours, show it to me, I say
yes or tweak it, and it posts. That's the whole win — no jumping to Jira, no writing
it up from memory, no reformatting by hand.
